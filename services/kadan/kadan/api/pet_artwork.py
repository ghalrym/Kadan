def base_prompt(description: str) -> str:
    return (
        f"Create one full-body character: {description.strip()}. Preserve the requested art style; "
        "any style is allowed. Front-facing relaxed neutral stance, one character only, entire body "
        "and all extremities visible. Leave generous empty space on every side and above for jumping. "
        "Use a completely flat pure magenta (#ff00ff) background, with no ground, shadows, text, border, "
        "or extra objects. Do not use magenta or near-magenta anywhere on the character."
    )


def row_prompt(description: str, row: PetRow) -> str:
    instructions = " ".join(
        f"Cell {i + 1}: {pose}." for i, pose in enumerate(row.poses)
    )
    return (
        f"Edit this exact {row.frame_count}-cell horizontal reference strip into animation poses for "
        f"the same character ({description.strip()}). Every cell is exactly 384x416 pixels. "
        "Keep the reference character's identity, proportions, colors, costume, and requested art style "
        "in every frame. Generate genuine new articulated poses; do not merely copy, translate, rotate, "
        "or scale a flat picture. Preserve the fixed camera, body scale, horizontal center in each cell, "
        "and floor baseline at y=368 (except airborne jump frames). Keep every extremity inside its cell "
        "with clear margins. No dividers, labels, text, extra characters or objects. Background must stay "
        "flat pure magenta (#ff00ff), without shadows; no magenta on the character. "
        "Read cells left to right. Up is screen top (0 degrees), right is 90, down is 180, left is 270. "
        f"{instructions}"
    )


def _png(data: bytes, expected: tuple[int, int] | None = None) -> Image.Image:
    try:
        with Image.open(BytesIO(data)) as image:
            if image.format != "PNG":
                raise ValueError("Expected a PNG image")
            if expected is not None and image.size != expected:
                raise ValueError(
                    f"Expected image dimensions {expected}, got {image.size}"
                )
            if image.width * image.height > 4096 * 4096:
                raise ValueError("Pet source image exceeds 16 megapixels")
            if getattr(image, "n_frames", 1) != 1:
                raise ValueError("Expected a single PNG frame")
            return image.convert("RGBA")
    except (UnidentifiedImageError, OSError, Image.DecompressionBombError) as exc:
        raise ValueError("Could not decode pet PNG") from exc


def _cutout(image: Image.Image) -> Image.Image:
    red, green, blue, alpha = image.split()
    # Flood only edge-connected chroma. Interior details with the same color stay.
    pink = ImageChops.darker(
        ImageChops.subtract(red, green), ImageChops.subtract(blue, green)
    )
    pink = pink.point(lambda value: 255 if value > 60 else 0)
    bright = ImageChops.darker(red, blue).point(lambda value: 255 if value > 130 else 0)
    candidate = ImageChops.lighter(
        ImageChops.multiply(pink, bright), alpha.point(lambda a: 255 if a == 0 else 0)
    )
    connected = Image.new("L", (image.width + 2, image.height + 2), 255)
    connected.paste(candidate, (1, 1))
    ImageDraw.floodfill(connected, (0, 0), 128)
    keep = connected.crop((1, 1, image.width + 1, image.height + 1)).point(
        lambda p: 0 if p == 128 else 255
    )
    result = image.copy()
    result.putalpha(ImageChops.multiply(alpha, keep))
    return result


def _bounds(image: Image.Image) -> tuple[int, int, int, int]:
    visible = image.getchannel("A").point(lambda a: 255 if a > 16 else 0)
    bounds = visible.getbbox()
    if bounds is None or visible.histogram()[255] < 64:
        raise ValueError("Pet frame is blank or contains too little visible artwork")
    left, top, right, bottom = bounds
    if left < 2 or top < 2 or right > image.width - 2 or bottom > image.height - 2:
        raise ValueError(
            "Pet artwork touches a cell boundary; regenerate with clear margins"
        )
    return bounds


def _encode(image: Image.Image, format: str = "PNG") -> bytes:
    output = BytesIO()
    image.save(
        output, format=format, **({"lossless": True} if format == "WEBP" else {})
    )
    return output.getvalue()


def prepare_base(png: bytes) -> bytes:
    image = _cutout(_png(png))
    character = image.crop(_bounds(image))
    character.thumbnail((260, 292), Image.Resampling.LANCZOS)
    canonical = Image.new("RGBA", SOURCE_CELL)
    canonical.paste(
        character, ((SOURCE_CELL[0] - character.width) // 2, 368 - character.height)
    )
    return _encode(canonical)


def source_strip(base_png: bytes, count: int) -> bytes:
    if not 1 <= count <= COLUMNS:
        raise ValueError("A source strip needs between one and eight cells")
    base = _png(base_png, SOURCE_CELL)
    _bounds(base)
    strip = Image.new("RGB", (SOURCE_CELL[0] * count, SOURCE_CELL[1]), BACKGROUND)
    for column in range(count):
        strip.paste(base, (column * SOURCE_CELL[0], 0), base)
    return _encode(strip)


def extract_row(png: bytes, row: PetRow) -> list[Image.Image]:
    strip = _png(png, (row.frame_count * SOURCE_CELL[0], SOURCE_CELL[1]))
    frames = []
    for column in range(row.frame_count):
        left = column * SOURCE_CELL[0]
        frame = _cutout(strip.crop((left, 0, left + SOURCE_CELL[0], SOURCE_CELL[1])))
        _bounds(frame)
        # Preserve the model's floor placement and jump height across whole cells.
        frames.append(frame.resize(CELL, Image.Resampling.LANCZOS))
    if len({frame.tobytes() for frame in frames}) == 1:
        raise ValueError(
            f"Row {row.name} repeats one image; animated poses must differ"
        )
    return frames


def assemble_atlas(rows: dict[str, bytes]) -> bytes:
    if set(rows) != {row.name for row in ROWS}:
        raise ValueError("Atlas needs exactly the nine animation and two look rows")
    atlas = Image.new("RGBA", (COLUMNS * CELL[0], len(ROWS) * CELL[1]))
    for row in ROWS:
        for column, frame in enumerate(extract_row(rows[row.name], row)):
            atlas.paste(frame, (column * CELL[0], row.index * CELL[1]))
    return _encode(atlas, "WEBP")
