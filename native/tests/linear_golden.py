import math
import struct

def f(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]

def bits(x):
    u = struct.unpack('<I', struct.pack('<f', x))[0]
    return (u + 0x7fff + ((u >> 16) & 1)) >> 16

def bf(x):
    return struct.unpack('<f', struct.pack('<I', bits(x) << 16))[0]

def sigmoid(x):
    e = f(math.exp(-abs(x)))
    return f(1 / f(1 + e)) if x >= 0 else f(e / f(1 + e))

def dot(a, b):
    return bf(sum(x*y for x, y in zip(a, b)))

def norm(x, w, offset=False):
    total = 0
    for v in x:
        total = f(total + f(v*v))
    # C++ CPU mean expression promotes size_t division to float.
    inv = f(1 / f(math.sqrt(f(f(total / len(x)) + f(1e-6)))))
    return [bf(f(f(v*inv)*f(1+z))) if offset else bf(f(bf(f(v*inv))*z)) for v,z in zip(x,w)]

inputs = [[1,2,-1],[-2,1,.5],[.5,-1,2],[1,.5,-2]]
q = [[1,.5,-.25],[-.5,1,.25],[.25,-.5,1],[1,.25,.5]]
k = [[.75,.25,1],[-.25,1,.5],[1,-.25,.75],[.5,1,-.25]]
v = [[.25*(h+1),.125*(j+1),(-1)**(h+j)*.125*(h+j+1)] for h in range(4) for j in range(3)]
z = [[(-1)**j*.125*(h+1),.25*(j+1),(-1)**h*.25] for h in range(4) for j in range(3)]
out = [[(-1)**(r+h+j)*.125*(1+(r+2*h+j)%4) for h in range(4) for j in range(3)] for r in range(3)]
input_norm = [.125,-.25,.5]
conv = [[-.25,.5,.75] if ch%3==1 else [.25,-.5,1] for ch in range(20)]
a = [[.25,-.125,.5],[-.5,.25,.125],[.125,.5,-.25],[.5,-.25,-.125]]
b = [[-.25,.5,.125],[.125,-.5,.25],[.5,.125,-.25],[-.125,.25,.5]]
logs = [-.5,0,.25,.5]
dt = [.25,-.125,.5,-.25]
gate = [.75,1.25,.5]

def encode(x):
    # Fixture coefficients are exactly E4M3FN representable (scale = 1).
    for byte in range(256):
        sign = -1 if byte & 128 else 1
        exp, mant = (byte >> 3) & 15, byte & 7
        if exp == 15 and mant == 7:
            continue
        value = sign * (mant*2**-9 if exp == 0 else (1+mant/8)*2**(exp-7))
        if value == x:
            return byte
    raise ValueError(x)

history = [[0.0]*3 for _ in range(20)]
state = [[[0.0]*3 for _ in range(2)] for _ in range(4)]
results = []
