    activated = []
    for ch in range(20):
        history[ch] = history[ch][1:]+[projected[ch]]
        raw = dot(history[ch],conv[ch])
        activated.append(bf(f(raw*sigmoid(raw))))
    queries,keys = [],[]
    for h in range(2):
        for dest,base,is_q in [(queries,2*h,True),(keys,4+2*h,False)]:
            pair = activated[base:base+2]
            denom = f(math.sqrt(f(f(f(pair[0]*pair[0])+f(pair[1]*pair[1]))+f(1e-6))))
            inv = f(1/denom)
            dest.append([f(f(t*inv)/f(math.sqrt(2))) if is_q else f(t*inv) for t in pair])
    core=[]
    for h in range(4):
        t=f(av[h]+dt[h]); soft=f(max(t,0)+f(math.log1p(f(math.exp(-abs(t))))))
        decay=f(math.exp(f(-f(math.exp(logs[h]))*soft)))
        beta=bf(sigmoid(bv[h])); key=keys[h//2]; query=queries[h//2]
        values=activated[8+3*h:11+3*h]
        old=state[h]
        # Independent matrix identity: decay*(I-beta*k*k^T)@old + beta*k*v^T.
        transform=[[decay*((1 if i==j else 0)-beta*key[i]*key[j]) for j in range(2)] for i in range(2)]
